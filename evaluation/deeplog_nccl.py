#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
DeepLog entry point for NCCL logs.

This is the NCCL counterpart of logbert/HDFS/deeplog.py and keeps the same
subcommands:
  - vocab
  - train
  - predict

Expected data files (generated by evaluation/data_process.py):
  output/nccl/train
  output/nccl/test_normal
  output/nccl/test_abnormal
"""

import sys
import os
import argparse
from pathlib import Path

import torch

EVAL_DIR = Path(__file__).parent.resolve()
sys.path.insert(0, str(EVAL_DIR / "logbert"))

from logdeep.models.lstm import Deeplog  # noqa: E402
from logdeep.tools.predict import Predicter  # noqa: E402
from logdeep.tools.train import Trainer  # noqa: E402
from logdeep.tools.utils import seed_everything  # noqa: E402
from logdeep.dataset.vocab import Vocab  # noqa: E402

OUTPUT_DIR = str((EVAL_DIR / "../output/nccl").resolve()) + "/"

# Config Parameters
options = dict()
options["output_dir"] = OUTPUT_DIR
options["train_vocab"] = OUTPUT_DIR + "train"
options["vocab_path"] = OUTPUT_DIR + "vocab.pkl"

options["device"] = "cuda" if torch.cuda.is_available() else "cpu"

# Sample
options["sample"] = "sliding_window"
options["window_size"] = 20
options["min_len"] = 10

options["train_ratio"] = 1
# Keep a non-zero validation split for tiny datasets.
options["valid_ratio"] = 0.2
options["test_ratio"] = 1

options["is_logkey"] = True
options["is_time"] = False

# Features
options["sequentials"] = options["is_logkey"]
options["quantitatives"] = False
options["semantics"] = False
options["parameters"] = options["is_time"]
options["feature_num"] = sum([
    options["sequentials"],
    options["quantitatives"],
    options["semantics"],
    options["parameters"],
])

# Model
options["input_size"] = 1
options["hidden_size"] = 64
options["num_layers"] = 2
options["embedding_dim"] = 50
# Will be overwritten from vocab.pkl when available.
options["vocab_size"] = 32
options["num_classes"] = options["vocab_size"]

# Train
options["batch_size"] = 64
options["accumulation_step"] = 1

options["optimizer"] = "adam"
options["lr"] = 0.001
options["max_epoch"] = 200
options["n_epochs_stop"] = 10
options["lr_step"] = (options["max_epoch"] - 20, options["max_epoch"])
options["lr_decay_ratio"] = 0.1

options["resume_path"] = None
options["model_name"] = "deeplog"
options["save_dir"] = options["output_dir"] + "deeplog/"

# Predict
options["model_path"] = options["save_dir"] + "bestloss.pth"
options["num_candidates"] = 9
options["threshold"] = None
options["gaussian_mean"] = 0
options["gaussian_std"] = 0

print("Features logkey:{} time:{}".format(options["is_logkey"], options["is_time"]))
print("Device:", options["device"])

seed_everything(seed=1234)


def _sync_vocab_size_from_file() -> None:
    """Update options['vocab_size']/['num_classes'] from vocab.pkl when present."""
    if os.path.exists(options["vocab_path"]):
        vocab = Vocab.load_vocab(options["vocab_path"])
        options["vocab_size"] = len(vocab)
        options["num_classes"] = len(vocab)


def build_model() -> Deeplog:
    _sync_vocab_size_from_file()
    return Deeplog(
        input_size=options["input_size"],
        hidden_size=options["hidden_size"],
        num_layers=options["num_layers"],
        vocab_size=options["vocab_size"],
        embedding_dim=options["embedding_dim"],
    )


def train() -> None:
    model = build_model()
    trainer = Trainer(model, options)
    trainer.start_train()


def predict() -> None:
    model = build_model()
    predicter = Predicter(model, options)
    predicter.predict_unsupervised()


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    subparsers = parser.add_subparsers(dest="mode")
    subparsers.required = True

    train_parser = subparsers.add_parser("train")
    train_parser.set_defaults(mode="train")

    predict_parser = subparsers.add_parser("predict")
    predict_parser.set_defaults(mode="predict")
    predict_parser.add_argument("--mean", type=float, default=0, help="error gaussian distribution mean")
    predict_parser.add_argument("--std", type=float, default=0, help="error gaussian distribution std")

    vocab_parser = subparsers.add_parser("vocab")
    vocab_parser.set_defaults(mode="vocab")

    args = parser.parse_args()
    print("arguments", args)

    if args.mode == "train":
        train()

    elif args.mode == "predict":
        options["gaussian_mean"] = args.mean
        options["gaussian_std"] = args.std
        predict()

    elif args.mode == "vocab":
        with open(options["train_vocab"], "r") as f:
            logs = f.readlines()
        vocab = Vocab(logs)
        print("vocab_size", len(vocab))
        vocab.save_vocab(options["vocab_path"])
